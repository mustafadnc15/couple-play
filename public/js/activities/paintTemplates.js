/**
 * Paint-by-number templates on an 800×600 canvas. Regions are SVG paths listed bottom to top:
 * a later region covers earlier ones. `c` is the palette index (shown to players as c + 1).
 * `lines` are decorative strokes that are not regions.
 */

const circle = (cx, cy, r) => `M${cx - r} ${cy} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0 Z`;
const rect = (x, y, w, h) => `M${x} ${y} h${w} v${h} h${-w} Z`;
const heart = (cx, cy, s) => {
  const k = s / 50;
  const p = (x, y) => `${cx + x * k} ${cy + y * k}`;
  return `M${p(0, -20)} C${p(0, -50)} ${p(-50, -50)} ${p(-50, -20)} C${p(-50, 10)} ${p(0, 30)} ${p(0, 50)} `
    + `C${p(0, 30)} ${p(50, 10)} ${p(50, -20)} C${p(50, -50)} ${p(0, -50)} ${p(0, -20)} Z`;
};
const cloud = (parts) => parts.map(([x, y, r]) => circle(x, y, r)).join(' ');

